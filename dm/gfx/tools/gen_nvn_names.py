#!/usr/bin/env python3
"""Generate the Intel host's C copy of the NVN name table."""

import json
import sys


names_path, out_path = sys.argv[1:3]
names = [line.strip() for line in open(names_path) if line.strip()]

with open(out_path, "w") as out:
    out.write("// Generated by dm/gfx/tools/gen_nvn_names.py; do not edit.\n")
    out.write(f"#define NVN_NFUNC {len(names)}\n\n")
    out.write("const char *nvn_names[NVN_NFUNC] = {\n")
    for name in names:
        out.write(f"    {json.dumps(name)},\n")
    out.write("};\n")